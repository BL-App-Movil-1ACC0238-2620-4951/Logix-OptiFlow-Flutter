/// Composition root: API, repositories and use cases.
class AppDependencies {
  AppDependencies({OptiFlowApi? api, SessionRepository? sessions}) : api = api ?? OptiFlowApi() {
    final patients = PatientRepositoryImpl(this.api);
    final stores = StoreRepositoryImpl(this.api);
    final appointments = AppointmentRepositoryImpl(this.api);
    final sessionRepository = sessions ?? SessionRepositoryImpl(SessionLocalDataSource());
    loginPatient = LoginPatient(patients);
    registerPatient = RegisterPatient(patients);
    loadSession = LoadSession(sessionRepository);
    saveSession = SaveSession(sessionRepository);
    clearSession = ClearSession(sessionRepository);
    loadReadNotifications = LoadReadNotifications(sessionRepository);
    saveReadNotifications = SaveReadNotifications(sessionRepository);
    loadSettings = LoadAppSettings(sessionRepository);
    saveSettings = SaveAppSettings(sessionRepository);
    getStores = GetOpticalStores(stores);
    searchStores = SearchOpticalStores(stores);
    getAvailability = GetStoreAvailability(stores);
    getAppointments = GetPatientAppointments(appointments);
    cancelAppointment = CancelAppointment(appointments);
    bookAppointment = BookAppointment(appointments);
    getWorkOrders = GetPatientWorkOrders(appointments);
    getClinicalRecords = GetPatientClinicalRecords(appointments);
    final catalog = CatalogRepositoryImpl(this.api);
    final inventory = InventoryRepositoryImpl(this.api);
    final staff = StaffRepositoryImpl(this.api);
    getFrames = GetFrames(catalog);
    getFrame = GetFrame(catalog);
    updateFramePrice = UpdateFramePrice(catalog);
    getStoreStock = GetStoreStock(inventory);
    getSuppliers = GetSuppliers(inventory);
    getStockMovements = GetStockMovements(inventory);
    replenishStock = ReplenishStock(inventory);
    getStaffPatients = GetStaffPatients(staff);
    getStaffPatient = GetStaffPatient(staff);
    registerPatientByStaff = RegisterPatientByStaff(staff);
    getPatientsWithRecords = GetPatientsWithRecords(staff);
    getStaffOrders = GetStaffOrders(staff);
    getAgenda = GetAgenda(staff);
    getProducts = GetProducts(staff);
    getProduct = GetProduct(staff);
    getProductionOrders = GetProductionOrders(staff);
    getStaffAlerts = GetStaffAlerts(staff);
    getReportBars = GetReportBars(staff);
  }

  final OptiFlowApi api;
  late final LoginPatient loginPatient;
  late final RegisterPatient registerPatient;
  late final LoadSession loadSession;
  late final SaveSession saveSession;
  late final ClearSession clearSession;
  late final LoadReadNotifications loadReadNotifications;
  late final SaveReadNotifications saveReadNotifications;
  late final LoadAppSettings loadSettings;
  late final SaveAppSettings saveSettings;
  late final GetOpticalStores getStores;
  late final SearchOpticalStores searchStores;
  late final GetStoreAvailability getAvailability;
  late final GetPatientAppointments getAppointments;
  late final CancelAppointment cancelAppointment;
  late final BookAppointment bookAppointment;
  late final GetPatientWorkOrders getWorkOrders;
  late final GetPatientClinicalRecords getClinicalRecords;
  late final GetFrames getFrames;
  late final GetFrame getFrame;
  late final UpdateFramePrice updateFramePrice;
  late final GetStoreStock getStoreStock;
  late final GetSuppliers getSuppliers;
  late final GetStockMovements getStockMovements;
  late final ReplenishStock replenishStock;
  late final GetStaffPatients getStaffPatients;
  late final GetStaffPatient getStaffPatient;
  late final RegisterPatientByStaff registerPatientByStaff;
  late final GetPatientsWithRecords getPatientsWithRecords;
  late final GetStaffOrders getStaffOrders;
  late final GetAgenda getAgenda;
  late final GetProducts getProducts;
  late final GetProduct getProduct;
  late final GetProductionOrders getProductionOrders;
  late final GetStaffAlerts getStaffAlerts;
  late final GetReportBars getReportBars;
}
